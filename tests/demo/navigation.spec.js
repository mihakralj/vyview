const { test, expect } = require('@playwright/test')
const AxeBuilder = require('@axe-core/playwright').default

test('all dashboard destinations are reachable from the mobile page index', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('navigation', { name: 'Page navigation' }).getByRole('link', { name: 'More' }).click()
  const index = page.locator('.results a')
  await expect(index).toHaveCount(17)
  const urls = await index.evaluateAll((links) => links.map((link) => link.href))
  for (const url of urls) {
    expect((await page.goto(url)).status()).toBe(200)
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), url).toBe(true)
  }
})

test('interfaces support filter, detail tabs, data ranges, and copy', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/interfaces?scoutTheme=dark')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  const types = page.getByRole('navigation', { name: 'Interface types' })
  await types.getByRole('link', { name: 'Ethernet' }).click()
  await types.getByRole('link', { name: 'VLAN' }).click()
  await expect(page.locator('tr.iface-row')).toHaveCount(7)
  await page.getByRole('searchbox', { name: 'Filter records' }).fill('ethernet')
  await page.getByRole('button', { name: 'Apply' }).click()
  await expect(page.locator('tr.iface-row')).toHaveCount(5)
  await page.getByRole('link', { name: 'eth3', exact: true }).click()
  const path = await page.locator('.detail-chart .chart-rx').getAttribute('d')
  await page.getByRole('link', { name: '7d', exact: true }).click()
  expect(await page.locator('.detail-chart .chart-rx').getAttribute('d')).not.toBe(path)
  await page.getByRole('navigation', { name: 'Section views' }).getByRole('link', { name: 'Optics' }).click()
  await page.getByRole('link', { name: 'Receive power' }).click()
  await expect(page.getByRole('heading', { name: 'Receive power · details' })).toBeVisible()
  await page.getByRole('button', { name: 'Copy value' }).first().click()
  await expect(page.getByRole('status')).toHaveText('Copied.')
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('-5.86 dBm')
  await page.getByRole('link', { name: 'Close details' }).click()
  await expect(page).not.toHaveURL(/sel=/)
})

test('palette can jump to a redacted diff record', async ({ page }) => {
  await page.goto('/')
  await page.keyboard.press('Control+k')
  const search = page.getByRole('searchbox', { name: 'Search dashboard' })
  await expect(search).toBeFocused()
  await search.fill('Authentication value')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await page.locator('.results').getByRole('link', { name: 'Authentication value' }).click()
  await expect(page).toHaveURL(/tab=diff/)
  await expect(page.getByRole('heading', { name: 'Authentication value · details' })).toBeVisible()
  await expect(page.locator('.inspector code')).toHaveText(['[REDACTED]', '[REDACTED]'])
})

test('longest-prefix lookup selects the most specific fixture route', async ({ page }) => {
  await page.goto('/routing')
  await page.getByRole('link', { name: 'RIB / FIB' }).click()
  await page.getByRole('textbox', { name: 'Destination address' }).fill('192.0.2.20')
  await page.getByRole('button', { name: 'Look up' }).click()
  await page.getByText('Best match:').getByRole('link', { name: '192.0.2.0/24' }).click()
  await expect(page.getByRole('link', { name: 'Open related evidence' })).toHaveAttribute('href', '/interfaces/eth4.20')
  const results = await new AxeBuilder({ page }).analyze()
  expect(results.violations.filter(({ impact }) => impact === 'serious' || impact === 'critical')).toEqual([])
})

test('topology evidence deep links and example journal replay work', async ({ page }) => {
  await page.goto('/topology')
  await page.getByRole('figure').getByRole('link', { name: /Remote peers/ }).click()
  await page.getByRole('link', { name: 'Open related evidence' }).click()
  await expect(page).toHaveURL(/\/vpn\/wireguard$/)
  await page.goto('/logs')
  const replay = page.getByRole('region', { name: 'Journal replay' })
  await replay.getByRole('button', { name: 'Play fixture' }).click()
  await expect(replay.getByRole('status')).toHaveText('1 of 3 entries shown.')
  await replay.getByRole('button', { name: 'Pause replay' }).click()
  await expect(replay.getByRole('status')).toHaveText('Replay paused. 1 of 3 entries shown.')
  await replay.getByRole('button', { name: 'Reset' }).click()
  await expect(replay.getByRole('listitem')).toHaveCount(0)
})

